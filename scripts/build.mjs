import { readFile, readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = path => readFile(resolve(root, path), 'utf8');
const { version } = JSON.parse(await read('package.json'));
const files = (await readdir(resolve(root, 'src/platforms'))).filter(file => file.endsWith('.js')).sort();
const platformSources = await Promise.all(files.map(file => read(`src/platforms/${file}`)));
// Keep the existing installation URL: userscript managers update by metadata version.
const output = resolve(root, 'yt4k-1.2.0.user.js');
const hosts = new Set();
for (const source of platformSources) {
  const declaration = source.match(/hosts:\s*\[([^\]]+)\]/);
  if (!declaration) throw new Error('Each adapter must declare its exact hosts');
  for (const match of declaration[1].matchAll(/['"]([^'"]+)['"]/g)) hosts.add(match[1]);
}
const metadata = [
  '// ==UserScript==',
  '// @name         yt4k',
  '// @namespace    https://localhost/yt-auto-max-quality',
  `// @version      ${version}`,
  '// @description  Automatically selects the highest supported video quality up to 2160p.',
  '// @author       you',
  ...[...hosts].sort().map(host => `// @match        https://${host}/*`),
  '// @exclude      https://www.youtube.com/embed/*',
  '// @exclude      https://m.youtube.com/embed/*',
  '// @grant        none',
  '// @sandbox      raw',
  '// @inject-into  page',
  '// @run-at       document-start',
  '// @noframes     true',
  '// ==/UserScript==',
];
const source = `${metadata.join('\n')}\n\n// Generated by npm run build. Edit src/ instead.\n(function () {\n  'use strict';\n\n${await read('src/core.js')}\n${platformSources.join('\n')}\nvoid YT4K.start(location.hostname);\n})();\n`;
if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== source) throw new Error('Userscript is stale; run npm run build');
  console.log('Userscript matches sources.');
} else {
  await writeFile(output, source);
  console.log(`Built yt4k with: ${files.join(', ')}`);
}
